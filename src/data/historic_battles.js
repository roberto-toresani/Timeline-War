// Kosovo), Mohi (1241 — l'Ungheria nord-orientale qui non esiste come
// provincia), Aljubarrota (1385 — fra Portugal e Beira), la Maritsa (1371),
// Kulikovo (1380), la Kalka (1223), Tarain e Panipat, Dorileo (1097).
// Chi aggiunge una riga applica lo stesso metro: nel dubbio, non si aggiunge.
//
// `provincia` è il NOME della provincia come lo mostra la mappa (lo stesso di
// data/map_data.js e dei valori di ID_MAP), non l'id dell'SVG: attenzione, i
// due differiscono in qualche caso (id `Northern_Serbia` → nome "Serbia",
// id `Estremadura` → nome "Portugal").
//
// L'abbinamento sito → provincia è stato controllato due volte: per nome della
// regione storica e, dove i riferimenti sulla mappa erano fitti, riproiettando

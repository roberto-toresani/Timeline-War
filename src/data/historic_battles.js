//
// Quando un giocatore attacca una provincia e nel DECENNIO di quel turno, in
// QUELLA STESSA provincia, si è combattuta davvero una battaglia, la cronaca
// la ricorda. Non cambia nulla del gioco: è una nota a margine.
//
// REGOLA D'INGRESSO (severa, apposta — un fatto storico sbagliato è peggio di
// un fatto storico assente):
//   1. anno e luogo del campo di battaglia devono essere accertati;
//   2. il sito deve cadere SENZA AMBIGUITÀ dentro la provincia indicata.
